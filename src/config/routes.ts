/**
 * Helper lookup to get route metadata by exact path
 */
export const getRouteByPath = (path: string): RouteDefinition | undefined => {
  const normalized = path === '' ? '/' : path.replace(/\/+$/, '') || '/';
  return APP_ROUTES.find((r) => r.path === normalized);
};
