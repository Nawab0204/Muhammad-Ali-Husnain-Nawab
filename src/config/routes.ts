/**
 * Master Registry of all application routes and sitemap definitions.
 * Ensures 100% synchronization between in-app routing, SEO canonical tags, and Google Search Console sitemaps.
 */

export interface RouteDefinition {
  path: string;
  title: string;
  description: string;
  category: 'core' | 'service-division' | 'service-subcategory' | 'portfolio' | 'case-study' | 'blog' | 'legal' | 'location';
  priority: number;
  changefreq: 'always' | 'hourly' | 'daily' | 'weekly' | 'monthly' | 'yearly' | 'never';
  parentPath?: string;
  breadcrumbLabel: string;
}

export const CANONICAL_ORIGIN = 'https://botlytices.com';

export const normalizeRoutePath = (path: string): string => {
  if (!path) return '/';
  let clean = path.trim();
  // Strip origin if mistakenly passed a full URL
  clean = clean.replace(/^https?:\/\/[^/]+/i, '');
  // Strip query string and hash
  clean = clean.split('?')[0].split('#')[0];
  if (!clean.startsWith('/')) clean = `/${clean}`;
  clean = clean.replace(/\/+$/, '');
  return clean || '/';
};

export const buildCanonicalUrl = (path: string, origin = CANONICAL_ORIGIN): string => {
  const base = origin.replace(/\/+$/, '');
  const normalized = normalizeRoutePath(path);
  return normalized === '/' ? `${base}/` : `${base}${normalized}`;
};

